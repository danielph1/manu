const assert=require('node:assert/strict');
const fs=require('node:fs');
const Module=require('node:module');
const ts=require('typescript');
const filename=require('node:path').resolve('lib/metricas/escopo.ts');
const js=ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod=new Module(filename,module);mod.filename=filename;mod.paths=module.paths;mod._compile(js,filename);
const {resolverEscopoMetricas,periodoMetricas,indiceQualidade,projetarCorpos}=mod.exports;
const u=(tipo,empresa_id=1,loja='001')=>({id:1,tipo,empresa_id,loja});
assert.throws(()=>resolverEscopoMetricas(u('vendedor'),null,null));
assert.throws(()=>resolverEscopoMetricas(u('superadmin'),null,null));
assert.equal(resolverEscopoMetricas(u('superadmin'),2,null).empresaId,2);
assert.equal(resolverEscopoMetricas(u('admin',2),1,'001').empresaId,2);
assert.equal(resolverEscopoMetricas(u('gerente',1,'ABC'),1,'OUTRA').loja,'ABC');
assert.equal(resolverEscopoMetricas(u('marketing',1),33,null).empresaId,1);
assert.equal(indiceQualidade({nome:'Maria Silva',telefone:'21988887777',veiculo:'Onix',mensagem:'Gostaria de financiar'}),100);
assert.equal(indiceQualidade({nome:'Sem nome'}),0);
assert.equal(indiceQualidade({nome:'Maria Silva',email:'a@b.com'}),50);
assert.equal(periodoMetricas('tudo').inicio,null);
assert.notEqual(periodoMetricas('mes').fim,null);
const hist=[{mes:'2026-05',carroceria:'suv',vendas:1},{mes:'2026-06',carroceria:'suv',vendas:1},{mes:'2026-08',carroceria:'suv',vendas:3}];
const pr=projetarCorpos(hist,new Date('2026-11-04T12:00:00Z'));
assert.equal(pr[0].amostra_suficiente,true);
assert.ok(pr[0].estimativa_mes_seguinte>0);
const fr=projetarCorpos([{mes:'2026-10',carroceria:'sedan',vendas:2}],new Date('2026-11-04T12:00:00Z'));
assert.equal(fr[0].estimativa_mes_seguinte,null);
