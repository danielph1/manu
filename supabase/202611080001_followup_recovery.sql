BEGIN;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS followup_status text;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS followup_motivo text;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS followup_em timestamptz;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS followup_por integer REFERENCES public.usuarios(id);
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS followup_optin boolean NOT NULL DEFAULT false;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS followup_optin_origem text;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS followup_optin_em timestamptz;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS followup_optout_em timestamptz;
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='leads_followup_status_check') THEN
  ALTER TABLE public.leads ADD CONSTRAINT leads_followup_status_check
    CHECK (followup_status IS NULL OR followup_status IN ('na_fila','followup','recusado'));
 END IF;
END $$;
CREATE INDEX IF NOT EXISTS aurox_leads_followup_empresa_idx ON public.leads(empresa_id,followup_status,vendedor_id);

CREATE TABLE IF NOT EXISTS public.aurox_followup_campanhas(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id integer NOT NULL REFERENCES public.empresas(id),
 criado_por integer NOT NULL REFERENCES public.usuarios(id),
 formato text NOT NULL CHECK (formato IN ('mensagem','lista_texto','enquete_texto')),
 titulo text NOT NULL,
 conteudo text NOT NULL,
 estado text NOT NULL DEFAULT 'ativa' CHECK(estado IN ('ativa','pausada','concluida')),
 criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS aurox_followup_campanhas_empresa_idx ON public.aurox_followup_campanhas(empresa_id,criado_em DESC);
CREATE TABLE IF NOT EXISTS public.aurox_followup_envios(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id integer NOT NULL REFERENCES public.empresas(id),
 campanha_id bigint NOT NULL REFERENCES public.aurox_followup_campanhas(id) ON DELETE CASCADE,
 lead_id integer NOT NULL REFERENCES public.leads(id),
 texto text NOT NULL,
 estado text NOT NULL DEFAULT 'pendente' CHECK(estado IN ('pendente','processando','enviado','ignorado','erro','cancelado')),
 agendado_em timestamptz NOT NULL,
 processado_em timestamptz,
 erro text,
 UNIQUE(campanha_id,lead_id)
);
CREATE INDEX IF NOT EXISTS aurox_followup_envios_pendentes_idx ON public.aurox_followup_envios(agendado_em,id) WHERE estado='pendente';
CREATE INDEX IF NOT EXISTS aurox_followup_envios_empresa_idx ON public.aurox_followup_envios(empresa_id,processado_em DESC);
CREATE TABLE IF NOT EXISTS public.aurox_followup_cadencia(
 empresa_id integer PRIMARY KEY REFERENCES public.empresas(id),
 ultima_reserva_em timestamptz
);
ALTER TABLE public.aurox_followup_campanhas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.aurox_followup_envios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.aurox_followup_cadencia ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.aurox_followup_campanhas,public.aurox_followup_envios,public.aurox_followup_cadencia FROM anon,authenticated;

ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS senha_alterada_em timestamptz;
CREATE TABLE IF NOT EXISTS public.aurox_senha_reset_tokens(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
 token_hash text NOT NULL UNIQUE,
 ip_hash text NOT NULL,
 criado_em timestamptz NOT NULL DEFAULT now(),
 expira_em timestamptz NOT NULL,
 usado_em timestamptz
);
CREATE INDEX IF NOT EXISTS aurox_senha_reset_usuario_idx ON public.aurox_senha_reset_tokens(usuario_id,criado_em DESC);
CREATE INDEX IF NOT EXISTS aurox_senha_reset_ip_idx ON public.aurox_senha_reset_tokens(ip_hash,criado_em DESC);
ALTER TABLE public.aurox_senha_reset_tokens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.aurox_senha_reset_tokens FROM anon,authenticated;

-- Transferências: empresa gravada no próprio registro; legado sem vínculo permanece restrito.
ALTER TABLE public.processos_transferencia ADD COLUMN IF NOT EXISTS empresa_id integer REFERENCES public.empresas(id);
WITH vinculo_unico AS (
 SELECT p.id AS processo_id,MIN(fat.empresa_id)::integer AS empresa_id
 FROM public.processos_transferencia p
 JOIN public.faturamentos fat ON fat.empresa_id IS NOT NULL AND
  ((p.ficha_id IS NOT NULL AND fat.ficha_id=p.ficha_id) OR
   (p.lead_id IS NOT NULL AND fat.lead_id=p.lead_id))
 WHERE p.empresa_id IS NULL
 GROUP BY p.id HAVING COUNT(DISTINCT fat.empresa_id)=1
)
UPDATE public.processos_transferencia p SET empresa_id=v.empresa_id
 FROM vinculo_unico v WHERE p.id=v.processo_id AND p.empresa_id IS NULL;
CREATE INDEX IF NOT EXISTS aurox_processos_empresa_idx ON public.processos_transferencia(empresa_id,id DESC);
COMMIT;
