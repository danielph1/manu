-- Aurox - Anuncio Coletivo: reutiliza autorizacoes e fila atual (sem criar fila paralela).
-- REQUER: migrations de Follow Up / auditoria / finalidades / status aplicadas.
-- Executar primeiro em homologacao, com backup.
BEGIN;
DO $$ BEGIN
  IF to_regclass('public.aurox_followup_campanhas') IS NULL OR
     to_regclass('public.aurox_followup_envios') IS NULL OR
     to_regclass('public.aurox_followup_permissoes') IS NULL OR
     to_regclass('public.aurox_auditoria_alteracoes') IS NULL THEN
    RAISE EXCEPTION 'Execute primeiro as migrations de Follow Up, multi-finalidades, auditoria e status';
  END IF;
END $$;
ALTER TABLE public.aurox_followup_campanhas
  ADD COLUMN IF NOT EXISTS origem text NOT NULL DEFAULT 'followup',
  ADD COLUMN IF NOT EXISTS segmento jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS media_path text,
  ADD COLUMN IF NOT EXISTS media_mime text,
  ADD COLUMN IF NOT EXISTS media_nome text;
ALTER TABLE public.aurox_followup_campanhas DROP CONSTRAINT IF EXISTS aurox_followup_campanhas_origem_check;
ALTER TABLE public.aurox_followup_campanhas ADD CONSTRAINT aurox_followup_campanhas_origem_check
  CHECK (origem IN ('followup','coletivo'));
ALTER TABLE public.aurox_followup_campanhas DROP CONSTRAINT IF EXISTS aurox_followup_campanhas_midia_coerente;
ALTER TABLE public.aurox_followup_campanhas ADD CONSTRAINT aurox_followup_campanhas_midia_coerente
  CHECK ((media_path IS NULL AND media_mime IS NULL AND media_nome IS NULL) OR
    (media_path IS NOT NULL AND media_mime IN ('image/jpeg','image/png','video/mp4') AND media_nome IS NOT NULL));
CREATE TABLE IF NOT EXISTS public.aurox_coletivo_midia (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL REFERENCES public.empresas(id),
  criado_por integer NOT NULL REFERENCES public.usuarios(id),
  path text NOT NULL UNIQUE,
  mime text NOT NULL CHECK(mime IN ('image/jpeg','image/png','video/mp4')),
  bytes_esperados integer NOT NULL CHECK(bytes_esperados BETWEEN 100 AND 8000000),
  criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS aurox_coletivo_midia_empresa_idx ON public.aurox_coletivo_midia(empresa_id,id DESC);
CREATE INDEX IF NOT EXISTS aurox_coletivo_campanhas_empresa_idx ON public.aurox_followup_campanhas(empresa_id,id DESC) WHERE origem='coletivo';
ALTER TABLE public.aurox_coletivo_midia ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.aurox_coletivo_midia FROM anon,authenticated;
COMMENT ON TABLE public.aurox_coletivo_midia IS 'Midias privadas de campanhas por empresa, com upload temporario assinado. Retencao sujeita a politica de privacidade.';
COMMIT;
