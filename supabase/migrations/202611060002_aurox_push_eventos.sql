-- Execute no SQL Editor com a role postgres. Não altera dados dos leads.
BEGIN;
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS preferencias_notif jsonb NOT NULL DEFAULT '{}'::jsonb;
CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  endpoint text NOT NULL UNIQUE,
  p256dh text NOT NULL,
  auth text NOT NULL,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
-- Compatível com quem criou a tabela em versões anteriores.
ALTER TABLE public.push_subscriptions ADD COLUMN IF NOT EXISTS ativo boolean DEFAULT true;
ALTER TABLE public.push_subscriptions ADD COLUMN IF NOT EXISTS updated_at timestamptz DEFAULT now();
CREATE INDEX IF NOT EXISTS aurox_push_sub_usuario ON public.push_subscriptions(usuario_id) WHERE ativo = true;
ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.push_subscriptions FROM anon, authenticated;

CREATE TABLE IF NOT EXISTS public.aurox_push_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notificacao_id bigint UNIQUE,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  titulo text NOT NULL,
  mensagem text NOT NULL,
  destino text NOT NULL DEFAULT '/painel',
  tipo text NOT NULL DEFAULT 'geral',
  estado text NOT NULL DEFAULT 'pendente' CHECK (estado IN ('pendente','processando','enviado','ignorado','erro')),
  tentativas integer NOT NULL DEFAULT 0,
  proxima_tentativa timestamptz NOT NULL DEFAULT now(),
  bloqueado_em timestamptz,
  processado_em timestamptz,
  erro text,
  criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS aurox_push_outbox_pendente ON public.aurox_push_outbox(proxima_tentativa,id)
  WHERE estado IN ('pendente','processando');
ALTER TABLE public.aurox_push_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.aurox_push_outbox FROM anon, authenticated;

-- Todos os inserts existentes na tabela de notificações geram entrega push durável.
-- Falha no envio nunca bloqueia inserção do aviso de origem.
CREATE OR REPLACE FUNCTION public.aurox_push_enfileirar_notificacao() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
  INSERT INTO public.aurox_push_outbox(notificacao_id,usuario_id,titulo,mensagem,tipo,destino)
  VALUES (NEW.id,NEW.usuario_id,COALESCE(NEW.titulo,'Aurox'),'Abra o Aurox para ver os detalhes.',
          COALESCE(NEW.tipo,'geral'),
          CASE WHEN lower(COALESCE(NEW.tipo,'')) LIKE '%chat%' THEN '/chat'
               WHEN lower(COALESCE(NEW.tipo,'')) LIKE '%tarefa%' THEN '/tarefas'
               WHEN lower(COALESCE(NEW.tipo,'')) LIKE '%ficha%' THEN '/fichas'
               WHEN lower(COALESCE(NEW.tipo,'')) LIKE '%fatura%' THEN '/faturamento'
               WHEN lower(COALESCE(NEW.tipo,'')) LIKE '%lead%' THEN '/painel'
               ELSE '/painel' END)
  ON CONFLICT (notificacao_id) DO NOTHING;
  RETURN NEW;
END;$$;
DROP TRIGGER IF EXISTS aurox_push_on_notificacoes ON public.notificacoes;
CREATE TRIGGER aurox_push_on_notificacoes AFTER INSERT ON public.notificacoes
FOR EACH ROW EXECUTE FUNCTION public.aurox_push_enfileirar_notificacao();

-- Novas mensagens que entram no chat por integrações: avisa somente o vendedor responsável.
CREATE OR REPLACE FUNCTION public.aurox_push_mensagem_cliente() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE u_id integer;
BEGIN
  IF NEW.remetente_id IS NOT NULL OR NEW.lead_id IS NULL OR
     COALESCE(NEW.mensagem,'') LIKE '[interno]%' THEN RETURN NEW; END IF;
  SELECT u.id INTO u_id FROM public.leads l
    JOIN public.vendedores v ON v.id=l.vendedor_id
    JOIN public.usuarios u ON u.vendedor_id=v.id AND u.empresa_id=v.empresa_id
   WHERE l.id=NEW.lead_id AND COALESCE(u.ativo,true)=true AND COALESCE(u.status,'ativo')='ativo'
   ORDER BY u.id LIMIT 1;
  IF u_id IS NOT NULL THEN
    INSERT INTO public.notificacoes(usuario_id,tipo,titulo,mensagem)
      VALUES(u_id,'chat','Nova mensagem recebida','Um cliente enviou uma mensagem no chat.');
  END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Push chat: %',SQLERRM;
  RETURN NEW;
END;$$;
DROP TRIGGER IF EXISTS aurox_push_chat_cliente ON public.chat_geral_mensagens;
CREATE TRIGGER aurox_push_chat_cliente AFTER INSERT ON public.chat_geral_mensagens
FOR EACH ROW EXECUTE FUNCTION public.aurox_push_mensagem_cliente();

-- Lead criado na triagem, sem compartilhar nome ou telefone na notificação de bloqueio de tela.
CREATE OR REPLACE FUNCTION public.aurox_push_triagem_nova() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
  IF NEW.empresa_id IS NOT NULL AND COALESCE(NEW.status,'aguardando')='aguardando' THEN
    INSERT INTO public.notificacoes(usuario_id,tipo,titulo,mensagem)
    SELECT u.id,'lead','Novo lead na triagem','Um contato aguarda distribuição na empresa.'
      FROM public.usuarios u
     WHERE u.empresa_id=NEW.empresa_id AND COALESCE(u.ativo,true)=true AND COALESCE(u.status,'ativo')='ativo'
       AND LOWER(COALESCE(u.tipo,'')) IN ('admin','gerente','marketing','superadmin');
  END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Push triagem: %',SQLERRM;
  RETURN NEW;
END;$$;
DROP TRIGGER IF EXISTS aurox_push_triagem ON public.triagem;
CREATE TRIGGER aurox_push_triagem AFTER INSERT ON public.triagem
FOR EACH ROW EXECUTE FUNCTION public.aurox_push_triagem_nova();

-- Novo lead criado diretamente: alerta o vendedor atribuído àquela empresa.
CREATE OR REPLACE FUNCTION public.aurox_push_lead_atribuido() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE u_id integer;
BEGIN
  IF NEW.vendedor_id IS NULL THEN RETURN NEW; END IF;
  SELECT u.id INTO u_id FROM public.vendedores v JOIN public.usuarios u
    ON u.vendedor_id=v.id AND u.empresa_id=v.empresa_id
    WHERE v.id=NEW.vendedor_id AND COALESCE(u.ativo,true)=true AND COALESCE(u.status,'ativo')='ativo' ORDER BY u.id LIMIT 1;
  IF u_id IS NOT NULL THEN
    INSERT INTO public.notificacoes(usuario_id,tipo,titulo,mensagem)
      VALUES(u_id,'lead','Novo lead atribuído','Um novo atendimento foi atribuído a você.');
  END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Push lead: %',SQLERRM;
  RETURN NEW;
END;$$;
DROP TRIGGER IF EXISTS aurox_push_novo_lead ON public.leads;
CREATE TRIGGER aurox_push_novo_lead AFTER INSERT ON public.leads
FOR EACH ROW EXECUTE FUNCTION public.aurox_push_lead_atribuido();

COMMIT;
