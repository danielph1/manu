-- Aurox-WhatsApp | WhatsApp Web autogerenciado / multiempresa.
-- Backup antes. Migration aditiva: nao modifica Z-API, Meta, leads antigos ou fichas.
BEGIN;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.aurox_wa_instancias (
  empresa_id integer PRIMARY KEY REFERENCES public.empresas(id),
  instancia_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  habilitada boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'desconectado'
    CHECK (status IN ('desconectado','iniciando','qr','autenticando','conectado','erro')),
  numero text,
  saudacao_ativa boolean NOT NULL DEFAULT false,
  saudacao text NOT NULL DEFAULT 'Olá! Recebemos sua mensagem. Em breve nossa equipe irá atender você.',
  criado_por integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  conectado_em timestamptz,
  ultima_mensagem_em timestamptz,
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  ultimo_erro text
);
-- Uma mesma linha de WhatsApp não pode pertencer a duas empresas simultaneamente.
CREATE UNIQUE INDEX IF NOT EXISTS aurox_wa_numero_unico
  ON public.aurox_wa_instancias(numero)
  WHERE habilitada AND numero IS NOT NULL AND numero <> '';

CREATE TABLE IF NOT EXISTS public.aurox_wa_contatos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL REFERENCES public.empresas(id),
  chat_id text NOT NULL,
  telefone text,
  nome text,
  triagem_id bigint REFERENCES public.triagem(id) ON DELETE SET NULL,
  lead_id integer REFERENCES public.leads(id) ON DELETE SET NULL,
  criado_em timestamptz NOT NULL DEFAULT now(),
  ultima_mensagem_em timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aurox_wa_contato_empresa_chat_uq UNIQUE (empresa_id, chat_id)
);
CREATE INDEX IF NOT EXISTS aurox_wa_contatos_empresa_data_idx
  ON public.aurox_wa_contatos(empresa_id, ultima_mensagem_em DESC);

CREATE TABLE IF NOT EXISTS public.aurox_wa_mensagens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL REFERENCES public.empresas(id),
  contato_id bigint NOT NULL REFERENCES public.aurox_wa_contatos(id) ON DELETE CASCADE,
  mensagem_id text NOT NULL,
  direcao text NOT NULL DEFAULT 'recebida' CHECK (direcao IN ('recebida','enviada')),
  tipo text NOT NULL DEFAULT 'chat',
  corpo text NOT NULL DEFAULT '',
  recebida_em timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT aurox_wa_msg_empresa_externa_uq UNIQUE (empresa_id,mensagem_id)
);
CREATE INDEX IF NOT EXISTS aurox_wa_mensagens_contato_data_idx
  ON public.aurox_wa_mensagens(contato_id, recebida_em DESC);

-- Banco acessado somente pelo backend autenticado, nunca diretamente no navegador.
ALTER TABLE public.aurox_wa_instancias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.aurox_wa_contatos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.aurox_wa_mensagens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.aurox_wa_instancias, public.aurox_wa_contatos,
  public.aurox_wa_mensagens FROM anon, authenticated;
COMMIT;
