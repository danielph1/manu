const TABLES: Record<Lang, Dict> = { pt, en, es, de };

export function t(lang: Lang | string | null | undefined, key: string): string {
  const L = (['pt', 'en', 'es', 'de'].includes(String(lang)) ? lang : 'pt') as Lang;
  return TABLES[L][key] || TABLES.pt[key] || key;
}

export function normalizeLang(v: unknown): Lang {
  const s = String(v || 'pt').toLowerCase().slice(0, 2);
  if (s === 'en' || s === 'es' || s === 'de' || s === 'pt') return s;
  return 'pt';
}
